// Get the COLOR variables in Primitive, grouped by color family (neutral, brand…)
function fdCollectColors(primVars) {
  const colorVars = primVars.filter(v =>
    v.resolvedType === 'COLOR' && /(^|[\/.])color([\/.])/.test(v.name));
  const groups = {};
  const order = [];
  for (const v of colorVars) {
    const norm = v.name.replace(/\./g, '/');
    const idx = norm.indexOf('color/');
    const rest = norm.slice(idx + 'color/'.length);   // vd "neutral/500"
    const parts = rest.split('/');
    const step = parts[parts.length - 1];
    const group = parts.slice(0, parts.length - 1).join('/') || step;
    if (!groups[group]) { groups[group] = []; order.push(group); }
    groups[group].push({ v, step });
  }
  // sort steps: numbers first (ascending), names keep their original order
  for (const g of order) {
    groups[g].sort((a, b) => {
      const na = parseFloat(a.step), nb = parseFloat(b.step);
      const aNum = !isNaN(na), bNum = !isNaN(nb);
      if (aNum && bNum) return na - nb;
      if (aNum) return -1;
      if (bNum) return 1;
      return 0;
    });
  }
  return { order, groups };
}

