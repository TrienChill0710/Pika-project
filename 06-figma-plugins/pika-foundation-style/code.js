// === Variable lookup helper ===
// The Import Tokens plugin stores variable names as full paths (e.g. "elevation/1/color")
// or only the last part inside a group folder. Fuzzy match to be safe.
function findVarByName(vars, namePath) {
  const dotPath = namePath.replace(/\//g, '.');
  return vars.find(v =>
    v.name === namePath ||
    v.name === dotPath ||
    v.name.endsWith('/' + namePath) ||
    v.name.endsWith('.' + dotPath) ||
    v.name.replace(/\./g, '/').endsWith('/' + namePath) ||
    v.name.replace(/\//g, '.').endsWith('.' + dotPath)
  );
}

// Resolve a FLOAT variable's number, following aliases (Semantic → Primitive).
function resolveNumberSync(v) {
  if (!v) return null;
  try {
    const x = Object.values(v.valuesByMode)[0];
    if (typeof x === 'number') return x;
  } catch (e) {}
  return null;
}
let RESOLVE_CACHE = null;
function resolveNumber(v, fallback) {
  const direct = resolveNumberSync(v);
  if (direct !== null) return direct;
  // alias chain — walk it with the pre-loaded variable list
  try {
    let cur = v, guard = 0;
    while (cur && guard++ < 6) {
      const x = Object.values(cur.valuesByMode)[0];
      if (typeof x === 'number') return x;
      if (x && typeof x === 'object' && x.type === 'VARIABLE_ALIAS' && RESOLVE_CACHE) {
        cur = RESOLVE_CACHE.find(o => o.id === x.id);
      } else break;
    }
  } catch (e) {}
  return fallback;
}

// === Tab Effect: Check status ===
// Resolve the optional STRING "type" variable of a shadow layer (may be an alias to a Primitive) → Figma effect type.
async function resolveShadowType(typeVar) {
  if (!typeVar) return 'DROP_SHADOW';
  try {
    let val = Object.values(typeVar.valuesByMode)[0];
    let guard = 0;
    while (val && typeof val === 'object' && val.type === 'VARIABLE_ALIAS' && guard++ < 5) {
      const ref = await figma.variables.getVariableByIdAsync(val.id);
      val = ref ? Object.values(ref.valuesByMode)[0] : null;
    }
    return String(val).toLowerCase() === 'inner' ? 'INNER_SHADOW' : 'DROP_SHADOW';
  } catch (e) { return 'DROP_SHADOW'; }
}

// Variables needed: every layer × 5 required properties (x · y · blur · spread · color); `type` is optional.
// Pika: 4 levels × 1 layer × 5 required properties = 20 elevation variables in Semantic.
async function checkStatus() {
  divider();
  log('Status check…');

  const collections = await figma.variables.getLocalVariableCollectionsAsync();
  log('Local collections: ' + collections.map(c => c.name).join(', '));

  const semantic = collections.find(c => c.name === 'Semantic');
  if (!semantic) {
    log('❌ "Semantic" collection does not exist yet. Import the tokens first.');
    return;
  }

  const allVars = await figma.variables.getLocalVariablesAsync();
  const semVars = allVars.filter(v => v.variableCollectionId === semantic.id);
  const elevationVars = semVars.filter(v => /(^|[\.\/])elevation([\.\/])/.test(v.name));
  log('✓ Semantic: ' + semVars.length + ' vars');
  log('✓ Elevation vars: ' + elevationVars.length + ' (need ' + (ELEVATION_RECORDS.reduce((n, r) => n + r.layers.length, 0) * 5) + ' + optional type)');

  if (elevationVars.length > 0) {
    log('Sample name: "' + elevationVars[0].name + '"');
  }

  // Resolve test for each record (level × layer)
  let okLevels = 0;
  for (const rec of ELEVATION_RECORDS) {
    const layerStatus = [];
    let allLayersOK = true;
    for (const layer of rec.layers) {
      const prefix = 'elevation/' + rec.level + '/' + layer + '/';
      const f = {
        x:      findVarByName(semVars, prefix + 'x'),
        y:      findVarByName(semVars, prefix + 'y'),
        blur:   findVarByName(semVars, prefix + 'blur'),
        spread: findVarByName(semVars, prefix + 'spread'),
        color:  findVarByName(semVars, prefix + 'color')
      };
      const missing = Object.keys(f).filter(k => !f[k]);
      if (missing.length === 0) {
        layerStatus.push(layer + '✓');
      } else {
        layerStatus.push(layer + '⚠(' + missing.join(',') + ')');
        allLayersOK = false;
      }
    }
    if (allLayersOK) okLevels++;
    log('  elevation/' + rec.level + ': ' + layerStatus.join(' · '));
  }
  log('✓ Levels resolve OK: ' + okLevels + '/' + ELEVATION_RECORDS.length);

  const styles = await figma.getLocalEffectStylesAsync();
  const ours = styles.filter(s => s.getPluginData(PLUGIN_TAG_KEY) === PLUGIN_TAG_VALUE);
  log('✓ Effect Styles created by the plugin: ' + ours.length + '/' + ELEVATION_RECORDS.length);

  divider();
  log(okLevels === ELEVATION_RECORDS.length
    ? '→ Ready to Generate.'
    : '→ Elevation tokens incomplete — check the imported token JSON.');
}

// === Tab Effect: Generate ===
// Each level → 1 EffectStyle. Style.effects = array of N DROP_SHADOWs (1 per layer).
// First layer = the sharp one close to the element; later layers = softer and wider — Figma stacks them in array order.
async function generateEffectStyles() {
  divider();
  log('Generating Effect Styles…');

  const collections = await figma.variables.getLocalVariableCollectionsAsync();
  const semantic = collections.find(c => c.name === 'Semantic');
  if (!semantic) {
    log('❌ "Semantic" collection does not exist. Import the tokens first.');
    return;
  }

  const allVars = await figma.variables.getLocalVariablesAsync();
  const semVars = allVars.filter(v => v.variableCollectionId === semantic.id);

  const existingStyles = await figma.getLocalEffectStylesAsync();

  let created = 0;
  let updated = 0;
  let skipped = 0;

  for (const rec of ELEVATION_RECORDS) {
    // Build the effect list for each layer of this level
    const effects = [];
    let allLayersOK = true;
    const missingDetail = [];

    for (const layer of rec.layers) {
      const prefix = 'elevation/' + rec.level + '/' + layer + '/';
      const f = {
        x:      findVarByName(semVars, prefix + 'x'),
        y:      findVarByName(semVars, prefix + 'y'),
        blur:   findVarByName(semVars, prefix + 'blur'),
        spread: findVarByName(semVars, prefix + 'spread'),
        color:  findVarByName(semVars, prefix + 'color')
      };
      const missing = Object.keys(f).filter(k => !f[k]);
      if (missing.length) {
        allLayersOK = false;
        missingDetail.push(layer + ':' + missing.join(','));
        continue;
      }

      // Shadow type: elevation/{level}/{layer}/type → "inner" = INNER_SHADOW, otherwise DROP_SHADOW.
      const shadowType = await resolveShadowType(findVarByName(semVars, prefix + 'type'));

      // Build the effect — fallback values are overridden by bound variables.
      effects.push({
        type: shadowType,
        color: { r: 0, g: 0, b: 0, a: 0.1 },
        offset: { x: 0, y: 0 },
        radius: 0,
        spread: 0,
        visible: true,
        blendMode: 'NORMAL',
        boundVariables: {
          color:   { type: 'VARIABLE_ALIAS', id: f.color.id },
          offsetX: { type: 'VARIABLE_ALIAS', id: f.x.id },
          offsetY: { type: 'VARIABLE_ALIAS', id: f.y.id },
          radius:  { type: 'VARIABLE_ALIAS', id: f.blur.id },
          spread:  { type: 'VARIABLE_ALIAS', id: f.spread.id }
        }
      });
    }

    if (!allLayersOK) {
      log('⚠ Skip Elevation/' + rec.level + ' — missing: ' + missingDetail.join(' | '));
      skipped++;
      continue;
    }

    const styleName = 'Elevation/' + rec.level;
    const layerCount = effects.length;

    // Reuse the style if it exists and has the plugin tag (update mode)
    let style = existingStyles.find(s =>
      s.name === styleName &&
      s.getPluginData(PLUGIN_TAG_KEY) === PLUGIN_TAG_VALUE
    );

    if (style) {
      style.effects = effects;
      updated++;
      log('↻ Updated  ' + styleName + '  (' + layerCount + ' layer)');
    } else {
      style = figma.createEffectStyle();
      style.name = styleName;
      // Set pluginData BEFORE effects — if effects fail, the style still has the tag and can be wiped.
      style.setPluginData(PLUGIN_TAG_KEY, PLUGIN_TAG_VALUE);
      style.setPluginData('pika-type', 'elevation');
      style.setPluginData('pika-record', rec.level);
      style.setPluginData('pika-layers', String(layerCount));
      style.effects = effects;
      created++;
      log('✓ Created  ' + styleName + '  (' + layerCount + ' layer)');
    }
  }

  divider();
  log('Done: ' + created + ' created, ' + updated + ' updated, ' + skipped + ' skipped.');
  log('Open the Styles panel (right sidebar) → Effect Styles to check.');
}

// === Tab Effect: Wipe ===
async function wipeEffectStyles() {
  divider();
  log('Wiping Effect Styles created by the plugin…');

  const styles = await figma.getLocalEffectStylesAsync();
  let removed = 0;
  for (const s of styles) {
    if (s.getPluginData(PLUGIN_TAG_KEY) === PLUGIN_TAG_VALUE) {
      log('✗ Remove  ' + s.name);
      s.remove();
      removed++;
    }
  }
  log('Done: ' + removed + ' Effect Styles removed.');
}

// === Tab Text Style: Check status ===
async function checkTextStatus() {
  divider();
  log('Status check (Text Style)…');

  const collections = await figma.variables.getLocalVariableCollectionsAsync();
  const primitive = collections.find(c => c.name === 'Primitive');
  if (!primitive) {
    log('❌ "Primitive" collection does not exist yet.');
    return;
  }

  const allVars = await figma.variables.getLocalVariablesAsync();
  const primVars = allVars.filter(v => v.variableCollectionId === primitive.id);

  const familyVar = findVarByName(primVars, 'font/family/sans');
  log((familyVar ? '✓' : '⚠') + ' font/family/sans' + (familyVar ? '' : ' MISSING'));
  if (familyVar) log('  Sample name: "' + familyVar.name + '"');

  const famCount = ['sans', 'text', 'display'].filter(k => findVarByName(primVars, 'font/family/' + k)).length;
  log('✓ Families: ' + famCount + '/3 (sans · text · display)');

  const lsVar = findVarByName(primVars, 'font/letterSpacing/normal');
  log((lsVar ? '✓' : '⚠') + ' font/letterSpacing/normal' + (lsVar ? '' : ' MISSING'));

  const uniqueSizes = [];
  const uniqueLhs = [];
  for (const s of TEXT_STYLE_MAP) {
    if (uniqueSizes.indexOf(s.sizeKey) === -1) uniqueSizes.push(s.sizeKey);
    if (uniqueLhs.indexOf(s.lhKey) === -1) uniqueLhs.push(s.lhKey);
  }

  let foundSizes = 0;
  for (const sz of uniqueSizes) {
    if (findVarByName(primVars, 'font/size/' + sz)) foundSizes++;
  }
  log('✓ Sizes:        ' + foundSizes + '/' + uniqueSizes.length);

  let foundLhs = 0;
  for (const lh of uniqueLhs) {
    if (findVarByName(primVars, 'font/lineHeight/' + lh)) foundLhs++;
  }
  log('✓ LineHeights:  ' + foundLhs + '/' + uniqueLhs.length);

  const styles = await figma.getLocalTextStylesAsync();
  const ours = styles.filter(s =>
    s.getPluginData(PLUGIN_TAG_KEY) === PLUGIN_TAG_VALUE &&
    s.getPluginData('pika-type') === 'typography'
  );
  log('✓ Text Styles created by the plugin: ' + ours.length + '/' + TEXT_STYLE_MAP.length);

  divider();
  const allOK = familyVar && lsVar && foundSizes === uniqueSizes.length && foundLhs === uniqueLhs.length;
  log(allOK ? '→ Ready to Generate.' : '→ Font tokens incomplete — import the tokens again.');
}

// === Tab Text Style: Generate ===
async function generateTextStyles() {
  divider();
  log('Generating Text Styles…');

  const collections = await figma.variables.getLocalVariableCollectionsAsync();
  const primitive = collections.find(c => c.name === 'Primitive');
  const semantic = collections.find(c => c.name === 'Semantic');
  if (!primitive) {
    log('❌ "Primitive" collection does not exist.');
    return;
  }

  const allVars = await figma.variables.getLocalVariablesAsync();
  RESOLVE_CACHE = allVars;
  const primVars = allVars.filter(v => v.variableCollectionId === primitive.id);
  const semVars  = semantic ? allVars.filter(v => v.variableCollectionId === semantic.id) : [];
  log(semantic
    ? '✓ Semantic collection loaded — semantic typography aliases will be preferred.'
    : '⚠ Semantic collection not imported — binding primitives directly.');

  // Resolver: try the semantic path first, then the primitive path
  function lookupTypoVar(semPath, primPath) {
    if (semVars.length) {
      const v = findVarByName(semVars, semPath);
      if (v) return { variable: v, source: 'semantic' };
    }
    const v = findVarByName(primVars, primPath);
    return v ? { variable: v, source: 'primitive' } : { variable: null, source: null };
  }

  // Family + letterSpacing — shared by every text style
  const familyRes = lookupTypoVar('typography/font-family/sans', 'font/family/sans');
  const lsRes     = lookupTypoVar('typography/letter-spacing/normal', 'font/letterSpacing/normal');
  if (!familyRes.variable || !lsRes.variable) {
    log('❌ Missing font family or letterSpacing variable.');
    return;
  }
  log('  fontFamily ← ' + familyRes.source + ', letterSpacing ← ' + lsRes.source);

  // Per-weight global fallback (regular/medium/semibold/bold) — Pika's heaviest weight is Bold 700
  const weightVars = {
    regular:  findVarByName(primVars, 'font/weight/regular'),
    medium:   findVarByName(primVars, 'font/weight/medium'),
    semibold: findVarByName(primVars, 'font/weight/semibold'),
    bold:     findVarByName(primVars, 'font/weight/bold')
  };
  const weightsBound = Object.keys(weightVars).filter(k => weightVars[k]);
  if (weightsBound.length > 0) {
    const types = weightsBound.map(k => k + '=' + weightVars[k].resolvedType).join(', ');
    log('  font/weight/*: ' + types);
    // Figma TextStyle setBoundVariable only supports fontStyle (STRING) — there is NO fontWeight field
    const stringWeights = weightsBound.filter(k => weightVars[k].resolvedType === 'STRING');
    const floatWeights  = weightsBound.filter(k => weightVars[k].resolvedType === 'FLOAT');
    if (stringWeights.length === 4) {
      log('  ✓ Weight bindable (STRING) → fontStyle');
    } else if (floatWeights.length > 0) {
      log('  ⚠ Weight is FLOAT (numeric W3C DTCG) — Figma only binds STRING to fontStyle.');
      log('    → Add 4 STRING variables: font/style/regular, medium, semibold, bold (with Inter\'s style names).');
      log('    Or change font/weight/* to STRING. The plugin looks up font/style/* first.');
    }
  } else {
    log('  ⚠ NO font/weight/* — weight set as a literal, not bound.');
  }

  // Try font/style/* (STRING) alongside font/weight/* (FLOAT)
  const styleVars = {
    regular:  findVarByName(primVars, 'font/style/regular'),
    medium:   findVarByName(primVars, 'font/style/medium'),
    semibold: findVarByName(primVars, 'font/style/semibold'),
    bold:     findVarByName(primVars, 'font/style/bold')
  };
  const stylesBound = Object.keys(styleVars).filter(k => styleVars[k]);
  if (stylesBound.length > 0) {
    log('  ✓ Found font/style/* (STRING): ' + stylesBound.join(', ') + ' — will be used to bind fontStyle.');
  }

  // Resolve the family literal value (needed for loadFontAsync)
  let familyName = 'Inter';   // fallback only — the real value comes from font/family/sans
  try {
    const defaultMode = primitive.modes[0].modeId;
    const v = familyVar.valuesByMode[defaultMode];
    if (typeof v === 'string') familyName = v;
  } catch (e) {}
  log('Font family resolved: "' + familyName + '"');

  // Load Pika's 4 weights (Regular / Medium / Semibold / Bold). If one fails → skip the styles that use it.
  // Pika: Bold 700 → Amount/Hero/Display/Heading/Title · SemiBold 600 → Body-lg/Body-bold/Label-bold/MicroCaps/StatusBar · Medium 500 → Label/Caption/Micro · Regular 400 → Body.
  log('Loading fonts…');
  // Inter names its 600 weight "Semi Bold" (with a space) in Figma; other faces spell it
  // "Semibold" or "SemiBold". Try each alias and remember the real style name that loaded.
  const STYLE_ALIASES = {
    Regular:  ['Regular'],
    Medium:   ['Medium'],
    Semibold: ['Semi Bold', 'Semibold', 'SemiBold'],
    Bold:     ['Bold']
  };
  const loaded = { Regular: false, Medium: false, Semibold: false, Bold: false };
  const actualStyle = {};
  for (const ws of Object.keys(STYLE_ALIASES)) {
    for (const alias of STYLE_ALIASES[ws]) {
      try {
        await figma.loadFontAsync({ family: familyName, style: alias });
        loaded[ws] = true;
        actualStyle[ws] = alias;
        log('  ✓ Loaded ' + familyName + ' ' + alias);
        break;
      } catch (e) {}
    }
    if (!loaded[ws]) log('  ⚠ Could not load ' + familyName + ' ' + ws + ' — skipping the styles that use this weight.');
  }

  const existingStyles = await figma.getLocalTextStylesAsync();
  let created = 0, updated = 0, skipped = 0, lhLiteralCount = 0;

  for (const spec of TEXT_STYLE_MAP) {
    const fontStyle = WEIGHT_TO_STYLE[spec.weight];
    if (!loaded[fontStyle]) {
      log('⚠ Skip ' + spec.name + ' — font ' + fontStyle + ' not loaded.');
      skipped++;
      continue;
    }

    // Parse spec.name: "Title1" → semanticPath="title1" (1 level)
    //                   "Display/Small" → semanticPath="display/small" (2 levels, legacy)
    const parts = spec.name.split('/');
    const semanticPath = parts.map(p => p.toLowerCase()).join('/');
    // Backward-compat: group/sizeName for legacy 2-level paths (debugging logs)
    const group = parts[0].toLowerCase();
    const sizeName = parts.length > 1 ? parts[1].toLowerCase() : group;

    // Resolve via semantic alias first, fallback primitive
    const sizeRes = lookupTypoVar(
      'typography/' + semanticPath + '/font-size',
      'font/size/' + spec.sizeKey
    );
    const lhRes = lookupTypoVar(
      'typography/' + semanticPath + '/line-height',
      'font/lineHeight/' + spec.lhKey
    );
    if (!sizeRes.variable || !lhRes.variable) {
      log('⚠ Skip ' + spec.name + ' — missing size/lineHeight variable.');
      skipped++;
      continue;
    }

    // Per-style typography family/letterSpacing override (if semantic defines one)
    const styleFamilyRes = lookupTypoVar(
      'typography/' + semanticPath + '/font-family',
      'font/family/sans'
    );
    // Per-style lsKey from the spec (tight/normal/wide)
    const lsKey = spec.lsKey || 'normal';
    const styleLsRes = lookupTypoVar(
      'typography/' + semanticPath + '/letter-spacing',
      'font/letterSpacing/' + lsKey
    );
    const familyToBind = styleFamilyRes.variable || familyRes.variable;
    const lsToBind     = styleLsRes.variable     || lsRes.variable;

    // Weight: semantic typography.{path}.fontWeight first, then font/style/* (STRING), then font/weight/* (FLOAT)
    const semWeightVar = findVarByName(semVars, 'typography/' + semanticPath + '/font-weight');
    const styleVar = styleVars[spec.weight];
    const weightVar = weightVars[spec.weight];
    const sizeVar = sizeRes.variable;
    const lhVar = lhRes.variable;

    let style = existingStyles.find(s =>
      s.name === spec.name &&
      s.getPluginData(PLUGIN_TAG_KEY) === PLUGIN_TAG_VALUE &&
      s.getPluginData('pika-type') === 'typography'
    );
    const isUpdate = !!style;
    if (!style) {
      style = figma.createTextStyle();
      style.name = spec.name;
      style.setPluginData(PLUGIN_TAG_KEY, PLUGIN_TAG_VALUE);
      style.setPluginData('pika-type', 'typography');
      style.setPluginData('pika-spec', spec.name);
    }

    try {
      // Set literal values (font must be pre-loaded). Bound variables override them.
      style.fontName = { family: familyName, style: actualStyle[fontStyle] || fontStyle };
      style.fontSize = 16;

      // UNITS — Pika's tokens are CSS-true, Figma is not:
      //   lineHeight    1.08 / 1.28 / 1.45  = a CSS multiplier  → Figma PERCENT 108 / 128 / 145
      //   letterSpacing -2 / 0 / 7          = per-mille of em    → Figma PERCENT -2 / 0 / 7  (1:1)
      // So letterSpacing binds cleanly once the unit is PERCENT; lineHeight cannot bind
      // (a bound FLOAT is read in the current unit, and 1.08% ≠ 108%), so it is written as a
      // PERCENT literal resolved from the token. Change the token → re-run Generate.
      const lhMultiplier = resolveNumber(lhVar, 1.45);
      style.lineHeight    = { unit: 'PERCENT', value: Math.round(lhMultiplier * 100) };
      style.letterSpacing = { unit: 'PERCENT', value: 0 };

      // Bind properties to variables. Priority: semantic typography aliases > primitive.
      style.setBoundVariable('fontFamily',    familyToBind);
      style.setBoundVariable('fontSize',      sizeVar);
      style.setBoundVariable('letterSpacing', lsToBind);
      lhLiteralCount++;

      // fontStyle: only bindable to STRING. Priority:
      //   1. Semantic typography.{group}.{size}.font-weight (if STRING)
      //   2. Semantic/Primitive font/style/{weight} (STRING)
      //   3. font/weight/{weight} (only if STRING)
      let fontStyleBound = false;
      const candidates = [];
      if (semWeightVar) candidates.push({ v: semWeightVar, label: 'semantic typography weight' });
      if (styleVar)     candidates.push({ v: styleVar,     label: 'font/style/' + spec.weight });
      if (weightVar)    candidates.push({ v: weightVar,    label: 'font/weight/' + spec.weight });

      for (const cand of candidates) {
        if (cand.v.resolvedType === 'STRING') {
          try {
            style.setBoundVariable('fontStyle', cand.v);
            fontStyleBound = true;
            break;
          } catch (e) {
            log('  ⚠ Bind fontStyle fail (' + cand.label + '): ' + e.message);
          }
        }
      }
      if (!fontStyleBound && candidates.length > 0) {
        // Variables exist but are all FLOAT → log advice
        const types = candidates.map(c => c.label + '=' + c.v.resolvedType).join(', ');
        if (!isUpdate) log('  ℹ ' + spec.name + ' fontStyle literal (' + types + ' — Figma needs STRING)');
      }

      if (isUpdate) {
        updated++;
        log('↻ Updated  ' + spec.name + '  (' + fontStyle + ')');
      } else {
        created++;
        log('✓ Created  ' + spec.name + '  (' + fontStyle + ')');
      }
    } catch (e) {
      log('❌ Fail ' + spec.name + ': ' + e.message);
      skipped++;
    }
  }

  divider();
  log('Done: ' + created + ' created, ' + updated + ' updated, ' + skipped + ' skipped.');
  log('Binding priority: Semantic typography aliases > Primitive (font/* or font/style/*).');
  log('Bound: fontFamily · fontSize · letterSpacing (PERCENT) · fontStyle.');
  log('lineHeight: PERCENT literal on ' + lhLiteralCount + ' style(s) — the token is a CSS');
  log('  multiplier (1.08/1.28/1.45) and Figma reads a bound FLOAT in the current unit, so');
  log('  1.08 would mean 1.08%. Re-run Generate after changing a lineHeight token.');
  if (stylesBound.length === 4) {
    log('✓ All 5 properties bound: fontFamily · fontStyle · fontSize · lineHeight · letterSpacing.');
  } else {
    log('ℹ fontStyle needs a STRING variable. Currently:');
    log('  • If font/weight/* is FLOAT → fontStyle can NOT be bound (literal "Bold"/...)');
    log('  • Fix: create STRING variables in the Primitive collection:');
    log('      font/style/regular  = "Regular"');
    log('      font/style/medium   = "Medium"');
    log('      font/style/semibold = "Semibold"');
    log('      font/style/bold     = "Bold"');
    log('  • Inter names its 600 weight "Semi Bold" (with a space) in Figma.');
    log('  • Or in Semantic: typography/{group}/{size}/font-weight (STRING).');
    log('  • Then run Generate again to bind.');
  }
}

