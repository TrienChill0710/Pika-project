// RGBA float (0..1) → hex string (#RRGGBB, or #RRGGBBAA if alpha < 1)
function fdHex(c) {
  if (!c || typeof c.r !== 'number') return '—';
  const to = (n) => Math.round(Math.max(0, Math.min(1, n)) * 255).toString(16).padStart(2, '0').toUpperCase();
  let s = '#' + to(c.r) + to(c.g) + to(c.b);
  if (typeof c.a === 'number' && c.a < 0.999) s += to(c.a);
  return s;
}

// Pick an available font for labels (the project font may be missing → fallback)
async function fdPickFont() {
  const candidates = ['Inter', 'Roboto', 'Helvetica Neue', 'Arial'];
  for (const family of candidates) {
    try {
      await figma.loadFontAsync({ family, style: 'Regular' });
      let bold = 'Regular', medium = 'Regular';
      try { await figma.loadFontAsync({ family, style: 'Bold' }); bold = 'Bold'; } catch (e) {}
      try { await figma.loadFontAsync({ family, style: 'Medium' }); medium = 'Medium'; } catch (e) {}
      return { family, regular: 'Regular', bold, medium };
    } catch (e) { /* try the next family */ }
  }
  return null;
}

function fdText(font, chars, size, styleName, rgb) {
  const t = figma.createText();
  t.fontName = { family: font.family, style: styleName };
  t.characters = String(chars);
  t.fontSize = size;
  if (rgb) t.fills = [{ type: 'SOLID', color: rgb }];
  return t;
}

